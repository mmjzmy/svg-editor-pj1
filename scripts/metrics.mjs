import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
const stat = execFileSync('git', ['diff','--stat','final..HEAD'], {encoding:'utf8'});
mkdirSync('docs/metrics',{recursive:true}); writeFileSync('docs/metrics/generated.txt', `Generated by git diff final..HEAD on ${new Date().toISOString()}\n\n${stat}`);
console.log(stat);
